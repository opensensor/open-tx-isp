#!/usr/bin/env python3
"""diff_t30_ae_exposure_item.py VENDOR.ko [--header OUT.h]: system item 16 written by the vendor AE (Lu-Fi/openimp#202).

Runs the SDK-built tx-isp-t30.ko ae_calculate_exposure (0x31cdc) in Unicorn with stab[1] = 0 (automatic
exposure) on random PI states.  The vendor stores math_exp2(exposure, 16, 6) of the clamped (>= 0) Q16 log2
exposure into stab+16 (sw v0,16(stab) at 0x31ec0) before it tail-calls cmos_set_exposure_target(cmos, exposure,
ratio).  Item 16 backs IMP_ISP_Tuning_GetEVAttr().ev (apical_isp_ev_g_attr, SYSTEM_MANUAL_EXPOSURE_TIME).
Each case records (exposure passed to cmos_set_exposure_target, stab item 16); --header writes them as a C
table for tests/t30_ae_gain_host_test.c, which checks t30_ae_exposure_time_item() against it.
"""
import sys, random, struct, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ko_emu import KoEmu
from unicorn.mips_const import UC_MIPS_REG_A0, UC_MIPS_REG_A1, UC_MIPS_REG_A2, UC_MIPS_REG_A3

def s64(x): return x - (1 << 64) if x >> 63 else x

def main():
    ko = sys.argv[1]
    out = sys.argv[sys.argv.index("--header") + 1] if "--header" in sys.argv else None
    st = {'read': 0, 'cap': None}
    def div64(e):
        n = s64(e.get_reg(UC_MIPS_REG_A0) | e.get_reg(UC_MIPS_REG_A1) << 32)
        d = s64(e.get_reg(UC_MIPS_REG_A2) | e.get_reg(UC_MIPS_REG_A3) << 32)
        q = int(n / d) if d else 0
        q &= (1 << 64) - 1
        return (q & 0xffffffff, q >> 32)
    def cap(e): st['cap'] = e.get_reg(UC_MIPS_REG_A1); return 0
    hle = {"APICAL_READ_32": lambda e: st['read'], "printk": lambda e: 0, "div64_s64": div64,
           "_GET_HDR_TABLE_INDEX": lambda e: 0, "_GET_UINT_PTR": lambda e: st['pi'],
           "cmos_set_exposure_target": cap, "ae_calculate_exposure_ratio": lambda e: 0}
    e = KoEmu(ko, hle=hle, max_insns=200000)
    for n in ("APICAL_READ_32", "_GET_HDR_TABLE_INDEX", "_GET_UINT_PTR", "cmos_set_exposure_target",
              "ae_calculate_exposure_ratio"):
        if n in e.symaddr: e.stubname[e.symaddr[n]] = n
    stab = e.symaddr["stab"]
    cmos = e.alloc(0x1600); fsm = e.alloc(0x40); st['pi'] = e.alloc(4)
    rnd = random.Random(202)
    rows = []; bad = 0
    for k in range(3000):
        e.write(stab, bytes(0x3c))                       # stab[1] = 0: automatic exposure
        e.write(st['pi'], struct.pack("<I", rnd.choice([1, 2, 4, 8, 16, rnd.randrange(1, 64)])))
        e.write(fsm, struct.pack("<I", cmos))
        e.write(cmos + 100, struct.pack("<ii", rnd.randrange(0, 1 << 20), rnd.randrange(0, 1 << 19)))
        e.write(cmos + 740, struct.pack("<i", rnd.randrange(0, 1 << 19)))
        st['read'] = rnd.randrange(0, 1 << 32)
        err = rnd.randrange(-(1 << 18), 1 << 18)
        acc = rnd.choice([0, rnd.randrange(-(1 << 22), 1 << 24)])
        e.write(fsm + 16, struct.pack("<iiqq", err, 0, acc, 0))
        st['cap'] = None
        r = e.call("ae_calculate_exposure", fsm)
        item = struct.unpack("<I", e.read(stab + 16, 4))[0]
        if r.stop or st['cap'] is None:
            bad += 1; print("STOP case %d: %s" % (k, r.stop)); continue
        rows.append((st['cap'], item))
    print("ae_calculate_exposure: %d cases, %d stopped, %d distinct exposures" % (len(rows), bad, len(set(r[0] for r in rows))))
    if out:
        with open(out, "w") as f:
            f.write("/* generated by tools/ko_emu/diff_t30_ae_exposure_item.py from the SDK-built tx-isp-t30.ko\n"
                    " * (ae_calculate_exposure 0x31cdc, automatic exposure): { exposure log2 Q16, stab item 16 } */\n")
            f.write("static const unsigned int t30_vendor_ae_item16[][2] = {\n")
            for a, b in rows[:600]: f.write("\t{ %#x, %#x },\n" % (a, b))
            f.write("};\n")
    sys.exit(1 if bad or not rows else 0)

main()
