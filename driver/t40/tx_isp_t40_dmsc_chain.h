static void t40_dmsc_comb_fill(uintptr_t par, uintptr_t comb, uint32_t wdr)
{
	const uint16_t *off = t40_dmsc_comb_off[wdr != 0];
	unsigned int i;

	for (i = 0; i < 233; i++)
		DMSC_U32(comb + 4 * i) = (uint32_t)(par + off[i]);
}

