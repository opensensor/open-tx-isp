/*
 * sec: a writable copy of section 11 (T32_DMSC_SEC_BYTES); the writes go to w
 * (T32_DMSC_MAX_WRITES entries).  Returns the number of writes.
 */
static inline int t32_dmsc_init(u8 *sec, struct t32_front_write *w)
{
	u8 o[T32_DMSC_VALUES];
	unsigned int n = 0, k;

	if (t32_front_le32(sec) != T32_DMSC_ID)
		return -1;
	for (k = 0; k < T32_DMSC_VALUES; k++)
		o[k] = 0;
	for (k = 0; k < 340; k++) {
		if (t32_dmsc_map[k][0] == 8)
			o[t32_dmsc_map[k][2]] = t32_tp_intp_u8(1, 0, sec + t32_dmsc_map[k][1]);
		else
			t32_tp_put16(o + t32_dmsc_map[k][2], t32_tp_intp_u16(1, 0, sec + t32_dmsc_map[k][1]));
	}
	t32_dmsc_noref(sec, w, &n);
	t32_dmsc_ref(sec, o, w, &n);
	T32_FWR(w, n, 0x8010, 1);
	T32_FWR(w, n, 0x8000, T32_DMSC_ID);
	return (int)n;
}

