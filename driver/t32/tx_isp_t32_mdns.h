/* Scale of the four 12 bit thresholds (above 0x80 the vendor widens them, 16 bit arithmetic). */
static inline u32 t32_mdns_widen(u32 x)
{
	u16 v;

	if (x <= 0x80)
		return x;
	v = (u16)(x * 0x40 + 0xe0ff);
	return v > 0x1fff ? 0x1fff : v;
}

/* tisp_mdns_intp at the gain index 1.0: sec -> o (T32_MDNS_VALUES bytes, zeroed here) */
static inline void t32_mdns_intp(const u8 *sec, u8 *o)
{
	unsigned int k, a;

	for (k = 0; k < T32_MDNS_VALUES; k++)
		o[k] = 0;
	for (k = 0; k < 1631; k++) {
		if (t32_mdns_map[k][0] == 16)
			t32_tp_put16(o + t32_mdns_map[k][2], t32_tp_intp_u16(1, 0, sec + t32_mdns_map[k][1]));
		else if (t32_mdns_map[k][0] == 24)
			t32_tp_put16(o + t32_mdns_map[k][2], t32_tp_intp_u8(1, 0, sec + t32_mdns_map[k][1]));
		else
			o[t32_mdns_map[k][2]] = t32_tp_intp_u8(1, 0, sec + t32_mdns_map[k][1]);
	}
	for (a = 0x116; a <= 0x11c; a += 2)
		t32_tp_put16(o + a, t32_mdns_widen(t32_tp_le16(o + a)));
	/* 0xff means "100 %" for the two runs of 8 weights */
	for (a = 0x19a; a <= 0x1b6; a += 2)
		if (t32_tp_le16(o + a) == 0xff)
			t32_tp_put16(o + a, 0x100);
	for (a = 0x3bc; a <= 0x3d8; a += 2)
		if (t32_tp_le16(o + a) == 0xff)
			t32_tp_put16(o + a, 0x100);
}

/* tisp_mdns_reg_cfg_equation_dif / _smp_15 results (the vendor keeps them in globals) */
struct t32_mdns_eq {
	int y[8];
	int cutval;
	int segopt;
	int grp[16];
};

/* tisp_mdns_reg_cfg_equation_dif: eight y values on a line, cut at the end value */
static inline void t32_mdns_eq_dif(struct t32_mdns_eq *e, int p1, int p2, int p3, int p4)
{
	unsigned int a;
	int d, step, k;

	e->cutval = p1 != 0xff ? p1 : 0xfe;
	if (p2 <= e->cutval)
		p2 = e->cutval + 1;
	a = (unsigned int)(p4 - p3) * 0x2000;
	a = (int)a < 0 ? -a : a;
	d = (int)a / (p2 - e->cutval);
	step = (0x100 - p1) / 7;
	e->y[0] = p3;
	for (k = 1; k < 8; k++)
		e->y[k] = p4 - p3 < 1 ? p3 - (step * k * d) / 0x2000 : (step * k * d) / 0x2000 + p3;
	if (p4 - p3 < 1) {
		if (p3 <= p4)
			e->y[0] = p4;
		for (k = 1; k < 8; k++)
			if (e->y[k] <= p4)
				e->y[k] = p4;
	} else {
		if (p4 <= p3)
			e->y[0] = p4;
		for (k = 1; k < 8; k++)
			if (p4 <= e->y[k])
				e->y[k] = p4;
	}
	e->segopt = 0;
}

/* tisp_mdns_reg_cfg_equation_smp_15: 15 y values on a line plus the end value in grp[15] */
static inline void t32_mdns_eq_smp15(struct t32_mdns_eq *e, int p1, int p2, int p3, int p4)
{
	int k, acc = 0, d = p4 - p3, v;

	if (p1 > 0xe)
		p1 = 0xe;
	if (p2 <= p1)
		p2 = p1 + 1;
	if (p2 > 0xe)
		p2 = 0xf;
	for (k = 0; k < 15; k++) {
		if (p1 < k) {
			v = (acc - p1 * d) / (p2 - p1) + p3;
			e->grp[k] = (d > 0 ? v < p4 : p4 < v) ? v : p4;
		} else {
			e->grp[k] = p3;
		}
		acc += d;
	}
	e->grp[15] = p4;
}

