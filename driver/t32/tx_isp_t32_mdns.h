/*
 * sec: writable copy of section 16 (T32_MDNS_SEC_BYTES); width, height: the
 * frame size; memopt: the compression setting in 1/1000 (<= 1000 off,
 * 1100 .. 2000 on, as the ISP memory size); o: T32_MDNS_VALUES bytes of scratch.  The writes go to w
 * (T32_MDNS_MAX_WRITES entries); returns their number, -1 on a refusal.
 */
static inline int t32_mdns_init(u8 *sec, u32 width, u32 height, u32 memopt, u8 *o, struct t32_front_write *w)
{
	unsigned int n = 0, pass;
	int cmp = memopt > 1000;

	if (cmp && (memopt > 2000 || memopt % 100))
		return -1;
	if (!width || !height)
		return -1;
	t32_mdns_intp(sec, o);
	if (cmp)
		t32_mdns_cmp(width, height, memopt, w, &n);
	for (pass = 0; pass < 2; pass++) {
		if (!pass) {
			t32_mdns_func_en(sec, cmp, w, &n);
		}
		t32_mdns_regs(sec, o, width, height, w, &n);
		T32_FWR(w, n, 0xd014, 1);
		if (!pass) {
			T32_FWR(w, n, 0xd018, 1);	/* tisp_mdns_start */
			T32_FWR(w, n, 0xd014, 1);
			T32_FWR(w, n, 0xd014, 1);	/* end of tisp_mdns_par_refresh */
		}
	}
	T32_FWR(w, n, 0xd014, 1);	/* tisp_mdns_reg_trig */
	T32_FWR(w, n, 0xd084, 2);
	return (int)n;
}

